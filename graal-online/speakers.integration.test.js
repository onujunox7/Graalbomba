'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { createFixture, waitFor } = require('./speaker_fixture');

test('rotas de produção sincronizam duas caixas e restringem comandos e proximidade', { timeout: 20000 }, async t => {
  const f = await createFixture();
  t.after(() => f.close());
  const admin = await f.connect();
  const near = await f.connect();
  const far = await f.connect();
  f.players.get(far.id).x = 10000;
  admin.send({ op: 'place', x: 999999 });
  const first = await waitFor(() => admin.state()?.selected);
  admin.send({ op: 'add', id: first, url: 'https://youtu.be/jNQXAC9IVRw' });
  await waitFor(() => near.state()?.boxes[0]?.playing);
  assert.equal(near.state().boxes[0].x, 6705);
  assert.equal(near.state().boxes[0].tracks, undefined);
  assert.equal(far.state().boxes.length, 0);
  near.send({ op: 'remove', id: first, role: 2 });
  await waitFor(() => near.messages.find(m => m.t === 'speaker' && m.op === 'error'));
  assert.equal(f.speakers.state(f.players.get(admin.id)).boxes.length, 1);
  const file = near.state().boxes[0].current.file;
  const base = 'http://127.0.0.1:' + f.port;
  const head = await fetch(base + file, { method: 'HEAD' });
  assert.equal(head.status, 200);
  assert.equal(Number(head.headers.get('content-length')), f.track.bytes);
  const partial = await fetch(base + file, { headers: { Range: 'bytes=0-31' } });
  assert.equal(partial.status, 206);
  assert.equal((await partial.arrayBuffer()).byteLength, 32);
  const invalid = await fetch(base + file, { headers: { Range: 'bytes=999999999-' } });
  assert.equal(invalid.status, 416);
  assert.equal((await fetch(base + '/api/speaker/audio/../../secret')).status, 404);
  admin.send({ op: 'volume', id: first, volume: 34 });
  await waitFor(() => near.state()?.boxes[0]?.volume === 34);
  admin.send({ op: 'place' });
  const second = await waitFor(() => admin.state()?.selected !== first && admin.state()?.selected);
  assert.equal(admin.state().boxes.length, 2);
  admin.send({ op: 'remove', id: second });
  await waitFor(() => admin.state()?.boxes.length === 1);
  assert.equal(admin.state().boxes[0].id, first);
  near.ws.send(JSON.stringify({ t: 'u', x: 10000, y: 17104, hp: 60, s: 0.6 }));
  await waitFor(() => near.state()?.boxes.length === 0);
  admin.send({ op: 'remove', id: first });
  await waitFor(() => admin.state()?.boxes.length === 0);
  assert.equal((await fetch(base + file)).status, 404);
});
